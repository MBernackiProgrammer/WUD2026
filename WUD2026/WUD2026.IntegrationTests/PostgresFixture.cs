using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.FileProviders;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Logging.Abstractions;
using Microsoft.AspNetCore.Hosting;
using Npgsql;
using Testcontainers.PostgreSql;
using WUD2026.Data;
using WUD2026.Services;

namespace WUD2026.IntegrationTests;

public sealed class PostgresFixture : IAsyncLifetime
{
    private readonly PostgreSqlContainer container = new PostgreSqlBuilder("postgres:17-alpine")
        .WithDatabase("integration").WithUsername("tests").WithPassword("Integration_2026!").Build();
    private readonly string? externalConnection = Environment.GetEnvironmentVariable("WUD_TEST_POSTGRES");
    private readonly System.Collections.Concurrent.ConcurrentBag<string> databases = [];
    private string ConnectionString => externalConnection ?? container.GetConnectionString();
    public Task InitializeAsync() => externalConnection is null ? container.StartAsync() : Task.CompletedTask;
    public async Task DisposeAsync()
    {
        if (externalConnection is null) { await container.DisposeAsync(); return; }
        await using var connection = new NpgsqlConnection(externalConnection);
        await connection.OpenAsync();
        foreach (var name in databases)
        {
            // Only names generated by this fixture, never the source database.
            if (!System.Text.RegularExpressions.Regex.IsMatch(name, "^test_[a-f0-9]{32}$")) throw new InvalidOperationException("Invalid test database name.");
            await using var command = new NpgsqlCommand($"DROP DATABASE IF EXISTS {name} WITH (FORCE)", connection);
            await command.ExecuteNonQueryAsync();
        }
    }

    public async Task<TestDatabase> CreateDatabaseAsync(string? importPath = null, bool initialize = true)
    {
        var name = "test_" + Guid.NewGuid().ToString("N");
        await using var connection = new NpgsqlConnection(ConnectionString);
        await connection.OpenAsync();
        await using var command = new NpgsqlCommand($"CREATE DATABASE {name}", connection);
        await command.ExecuteNonQueryAsync();
        databases.Add(name);
        var connectionString = new NpgsqlConnectionStringBuilder(ConnectionString) { Database = name }.ToString();
        var factory = new PooledDbContextFactory<ContentDbContext>(new DbContextOptionsBuilder<ContentDbContext>()
            .UseNpgsql(connectionString).Options);
        var configuration = new ConfigurationBuilder().AddInMemoryCollection(new Dictionary<string, string?>
        {
            ["Content:FilePath"] = importPath,
            ["Content:PublicationIntervalSeconds"] = "1"
        }).Build();
        var initializer = new DatabaseInitializer(factory, new TestEnvironment(), configuration, NullLogger<DatabaseInitializer>.Instance);
        if (initialize) await initializer.InitializeAsync();
        return new TestDatabase(connectionString, factory, configuration, initializer);
    }
}

public sealed record TestDatabase(string ConnectionString, IDbContextFactory<ContentDbContext> Factory,
    IConfiguration Configuration, DatabaseInitializer Initializer)
{
    public MutableClock Clock { get; } = new();
    public IContentStore Store => new DatabaseContentStore(Factory, Clock);
}

public sealed class MutableClock : TimeProvider
{
    public DateTimeOffset Now { get; set; } = new(2026, 10, 17, 12, 0, 0, TimeSpan.Zero);
    public override DateTimeOffset GetUtcNow() => Now;
}

public sealed class TestEnvironment : IWebHostEnvironment
{
    public string ApplicationName { get; set; } = "WUD2026";
    public string EnvironmentName { get; set; } = Environments.Development;
    public string ContentRootPath { get; set; } = AppContext.BaseDirectory;
    public IFileProvider ContentRootFileProvider { get; set; } = new NullFileProvider();
    public string WebRootPath { get; set; } = AppContext.BaseDirectory;
    public IFileProvider WebRootFileProvider { get; set; } = new NullFileProvider();
}
